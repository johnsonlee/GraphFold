package io.johnsonlee.graphfold.engine.inputs

import io.johnsonlee.graphfold.engine.EngineConfiguration
import io.johnsonlee.graphfold.engine.GraphFoldEngine
import io.johnsonlee.graphfold.engine.Verdict
import io.johnsonlee.graphfold.engine.git.changedFile
import io.johnsonlee.graphfold.engine.PreparedAnalysisRequest
import java.nio.file.Files
import java.nio.file.Path
import javax.tools.ToolProvider
import org.eclipse.jgit.diff.Edit
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.CsvSource
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/** Explicit source associations improve locations while the full raw input still decides control coverage. */
class SourceInputSnapshotTest {
    @TempDir lateinit var temporary: Path

    @ParameterizedTest
    @CsvSource("false,false", "false,true", "true,false", "true,true")
    fun `direct compiled inputs fold without origin instrumentation and optional roots only affect attribution`(
        mapped: Boolean, enabled: Boolean,
    ) {
        val base = revision("base", 1, 7, mapped)
        val head = revision("head", 2, 7, mapped)
        val result = GraphFoldEngine(EngineConfiguration(temporary.resolve("analysis"))).analyze(
            PreparedAnalysisRequest(base, head, listOf(change()), fold(enabled)))
        assertEquals(if (enabled) Verdict.FAIL else Verdict.PASS, result.verdict, result.toString())
        assertEquals(1, result.metadata.obligations)
        assertEquals(if (enabled) 0 else 1, result.metadata.provedObligations)
        assertTrue(result.ruleAudits.all { it.matchedCallCount == 1 }, result.toString())
        assertEquals(mapped && enabled, result.findings.isNotEmpty(), result.toString())
        if (mapped && enabled) {
            assertEquals(setOf("business/Example.java"), result.findings.flatMap { it.locations }.map { it.path }.toSet())
        }
        if (!enabled || mapped) assertTrue(result.diagnostics.isEmpty(), result.toString())
        listOf(base, head).forEach { input ->
            assertTrue(input.inventory != null)
            assertTrue(input.scopes.values.all { it.originDirectory == null && it.originRunId == null })
        }
    }

    @Test fun `a mapped controlled edit cannot hide a separate unreported production bytecode change`() {
        val base = revision("base", 1, 7, true)
        val head = revision("head", 2, 8, true)
        val result = GraphFoldEngine(EngineConfiguration(temporary.resolve("analysis"))).analyze(
            PreparedAnalysisRequest(base, head, listOf(change()), fold(false)))
        assertEquals(Verdict.FAIL, result.verdict, result.toString())
        assertEquals(0, result.metadata.provedObligations)
        assertTrue(result.reasons.any { it.message.contains("Generated.value") }, result.toString())
        assertTrue(result.findings.isEmpty(), "Unmapped generated bytes must not borrow the controlled source location")
    }

    private fun revision(name: String, value: Int, generated: Int, mapped: Boolean): PreparedRevision {
        val root = Files.createDirectories(temporary.resolve(name))
        val sourceRoot = Files.createDirectories(root.resolve("business"))
        val source = Files.writeString(sourceRoot.resolve("Example.java"), """
            public class Example {
                public static boolean enabled() { return true; }
                public static int value() { return enabled() ? $value : 0; }
            }
        """.trimIndent())
        val other = Files.writeString(root.resolve("Generated.java"),
            "public class Generated { public static int value() { return $generated; } }")
        val classes = Files.createDirectories(root.resolve("compiled"))
        assertEquals(0, ToolProvider.getSystemJavaCompiler().run(null, null, null,
            "-g", "-d", classes.toString(), source.toString(), other.toString()))
        val roots = if (mapped) listOf(sourceRoot) else emptyList()
        return StaticInputSnapshots.prepareSource(name, root, root.resolve("prepared"),
            SourceInput(classes, roots, emptyList(), Runtime.version().feature(), roots.associateWith { listOf(classes) }))
    }

    private fun change() = changedFile("business/Example.java", "business/Example.java", edits = listOf(Edit(2, 3, 2, 3)))

    private fun fold(enabled: Boolean) = """
        version: 1
        folds:
          - match: {CallSite: {callee_class: Example, callee_name: enabled}}
            value: $enabled
    """.trimIndent()
}
