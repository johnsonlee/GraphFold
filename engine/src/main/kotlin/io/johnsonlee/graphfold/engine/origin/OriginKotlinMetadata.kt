/** Only structured metadata identities are changed; d1/d2 are regenerated by the metadata writer. */
internal fun remapKotlinOriginMetadata(annotation: AnnotationNode, remapper: Remapper, owners: Map<String, String>) {
    if (owners.all { it.key == it.value }) return
    val metadata = readOriginMetadata(annotation)
    val decoded = KotlinClassMetadata.readStrict(metadata)
    val mapper = MetadataOwners(remapper, owners)
    when (decoded) {
        is KotlinClassMetadata.Class -> mapper.typeDeclaration(decoded.kmClass)
        is KotlinClassMetadata.FileFacade -> {
            mapper.container(decoded.kmPackage)
            decoded.kmPackage.localDelegatedProperties.forEach(mapper::property)
        }
        is KotlinClassMetadata.MultiFileClassPart -> {
            mapper.container(decoded.kmPackage)
            decoded.kmPackage.localDelegatedProperties.forEach(mapper::property)
            decoded.facadeClassName = remapper.map(decoded.facadeClassName)
        }
        is KotlinClassMetadata.MultiFileClassFacade -> decoded.partClassNames = decoded.partClassNames.map(remapper::map)
        is KotlinClassMetadata.SyntheticClass -> decoded.kmLambda?.function?.let(mapper::function)
        else -> error("Unknown Kotlin metadata kind")
    }
    writeOriginMetadata(annotation, decoded.write())
}

private fun metadataIntegers(value: Any?): IntArray = when (value) {
    is IntArray -> value
    is List<*> -> value.map { requireNotNull(it as? Int) }.toIntArray()
    else -> intArrayOf()
}

private fun metadataStrings(value: Any?): Array<String> = when (value) {
    is Array<*> -> value.map { requireNotNull(it as? String) }.toTypedArray()
    is List<*> -> value.map { requireNotNull(it as? String) }.toTypedArray()
    null -> emptyArray()
    else -> error("Malformed metadata string array")
}

private fun readOriginMetadata(annotation: AnnotationNode): Metadata {
    val pairs = annotation.values.orEmpty().chunked(2)
    require(pairs.all { it.size == 2 && it[0] is String }) { "Malformed annotation fields" }
    val values = pairs.associate { it[0] as String to it[1] }
    val version = metadataIntegers(values["mv"])
    require(version.isNotEmpty()) { "Missing metadata schema" }
    require(version[0] < 2 || version[0] == 2 && version.getOrElse(1) { 0 } <= 1) {
        "Metadata schema is newer than the verified 2.1 schema"
    }
    return Metadata(kind = values["k"] as? Int ?: 1, metadataVersion = version,
        data1 = metadataStrings(values["d1"]), data2 = metadataStrings(values["d2"]),
        extraString = (values["xs"] as? String).orEmpty(), packageName = (values["pn"] as? String).orEmpty(),
        extraInt = values["xi"] as? Int ?: 0)
}

private fun writeOriginMetadata(annotation: AnnotationNode, encoded: Metadata) {
    val rewritten = annotation.values.orEmpty().toMutableList()
    fun replace(key: String, value: Any) {
        val index = rewritten.indices.step(2).firstOrNull { rewritten[it] == key }
        if (index == null) rewritten.addAll(listOf(key, value)) else rewritten[index + 1] = value
    }
    replace("d1", encoded.data1.toList())
    replace("d2", encoded.data2.toList())
    if ("xs" in rewritten || encoded.extraString.isNotEmpty()) replace("xs", encoded.extraString)
    annotation.values = rewritten
}

@OptIn(ExperimentalContextReceivers::class, ExperimentalContracts::class)
private class MetadataOwners(private val remapper: Remapper, owners: Map<String, String>) {
    private val names = owners.entries.flatMap { (old, new) ->
        val original = old.replace('.', '/')
        val target = new.replace('.', '/')
        listOf(original to target, ".$original" to ".$target",
            original.replace('$', '.') to target.replace('$', '.'),
            ".${original.replace('$', '.')}" to ".${target.replace('$', '.')}")
    }.toMap()

    fun typeDeclaration(type: KmClass) {
        type.name = names[type.name] ?: type.name
        type.anonymousObjectOriginName = type.anonymousObjectOriginName?.let(remapper::map)
        type.sealedSubclasses.replaceAll { names[it] ?: it }
        type.supertypes.forEach(::type)
        type.typeParameters.forEach(::parameter)
        type.contextReceiverTypes.forEach(::type)
        type.inlineClassUnderlyingType?.let(::type)
        type.constructors.forEach { constructor ->
            constructor.valueParameters.forEach(::valueParameter)
            constructor.signature = constructor.signature?.let(::methodSignature)
        }
        container(type)
        type.localDelegatedProperties.forEach(::property)
    }

    fun container(container: KmDeclarationContainer) {
        require(container.typeAliases.isEmpty()) { "Type aliases require an additional metadata origin model" }
        container.functions.forEach(::function)
        container.properties.forEach(::property)
    }

    fun function(function: KmFunction) {
        require(function.contract == null) { "Contracts require an additional metadata origin model" }
        function.typeParameters.forEach(::parameter)
        function.contextReceiverTypes.forEach(::type)
        function.receiverParameterType?.let(::type)
        function.valueParameters.forEach(::valueParameter)
        type(function.returnType)
        function.signature = function.signature?.let(::methodSignature)
        function.lambdaClassOriginName = function.lambdaClassOriginName?.let(remapper::map)
    }

    fun property(property: KmProperty) {
        property.typeParameters.forEach(::parameter)
        property.contextReceiverTypes.forEach(::type)
        property.receiverParameterType?.let(::type)
        property.setterParameter?.let(::valueParameter)
        type(property.returnType)
        property.fieldSignature = property.fieldSignature?.let { JvmFieldSignature(it.name, remapper.mapDesc(it.descriptor)) }
        property.getterSignature = property.getterSignature?.let(::methodSignature)
        property.setterSignature = property.setterSignature?.let(::methodSignature)
        property.syntheticMethodForAnnotations = property.syntheticMethodForAnnotations?.let(::methodSignature)
        property.syntheticMethodForDelegate = property.syntheticMethodForDelegate?.let(::methodSignature)
    }

    private fun type(type: KmType) {
        require(type.annotations.isEmpty()) { "Type annotations require an additional metadata origin model" }
        val classifier = type.classifier
        if (classifier is KmClassifier.Class) type.classifier = KmClassifier.Class(names[classifier.name] ?: classifier.name)
        type.arguments.forEach { it.type?.let(::type) }
        type.abbreviatedType?.let(::type)
        type.outerType?.let(::type)
        type.flexibleTypeUpperBound?.type?.let(::type)
    }

    private fun parameter(parameter: KmTypeParameter) {
        require(parameter.annotations.isEmpty()) { "Type parameter annotations require an additional metadata origin model" }
        parameter.upperBounds.forEach(::type)
    }

    private fun valueParameter(parameter: KmValueParameter) {
        type(parameter.type)
        parameter.varargElementType?.let(::type)
    }

    private fun methodSignature(signature: JvmMethodSignature): JvmMethodSignature =
        JvmMethodSignature(signature.name, remapper.mapMethodDesc(signature.descriptor))
}
